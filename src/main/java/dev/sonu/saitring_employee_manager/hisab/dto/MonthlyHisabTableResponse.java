package dev.sonu.saitring_employee_manager.hisab.dto;

import io.swagger.v3.oas.annotations.media.Schema;

import java.math.BigDecimal;
import java.util.List;

@Schema(description = "Paginated monthly tabular running hisab response for owner view")
public class MonthlyHisabTableResponse {

    @Schema(description = "Month in YYYY-MM format", example = "2026-10")
    private String month;

    @Schema(description = "Total number of days in this month", example = "31")
    private int daysInMonth;

    @Schema(description = "Total eligible active employees in this month across all pages", example = "25")
    private int totalEligibleEmployees;

    @Schema(description = "Sum of full days worked by all employees on this page/month", example = "450")
    private int totalFullDays;

    @Schema(description = "Sum of half days worked by all employees on this page/month", example = "30")
    private int totalHalfDays;

    @Schema(description = "Sum of effective presenties worked across the organization in this month", example = "465.0")
    private double totalEffectivePresenties;

    @Schema(description = "Total earnings/wages generated by all workers across the organization in this month", example = "279000.00")
    private BigDecimal totalOrganizationEarnings;

    @Schema(description = "Total advance money deducted across all workers in this month", example = "45000.00")
    private BigDecimal totalOrganizationAdvance;

    @Schema(description = "Total final money payable to workforce in this month (totalEarnings - totalAdvance)", example = "234000.00")
    private BigDecimal totalOrganizationFinalMoney;

    @Schema(description = "Current page number (0-based)", example = "0")
    private int pageNumber;

    @Schema(description = "Page size", example = "20")
    private int pageSize;

    @Schema(description = "Total number of employee records across all pages", example = "25")
    private long totalElements;

    @Schema(description = "Total number of pages", example = "2")
    private int totalPages;

    @Schema(description = "Whether this is the first page", example = "true")
    private boolean first;

    @Schema(description = "Whether this is the last page", example = "false")
    private boolean last;

    @Schema(description = "Whether a next page exists", example = "true")
    private boolean hasNext;

    @Schema(description = "Whether a previous page exists", example = "false")
    private boolean hasPrevious;

    @Schema(description = "List of employee hisab rows for the current page")
    private List<HisabTableRow> employees;

    public MonthlyHisabTableResponse() {
    }

    public MonthlyHisabTableResponse(String month, int daysInMonth, int totalEligibleEmployees,
                                     int totalFullDays, int totalHalfDays, double totalEffectivePresenties,
                                     BigDecimal totalOrganizationEarnings, BigDecimal totalOrganizationAdvance,
                                     BigDecimal totalOrganizationFinalMoney,
                                     int pageNumber, int pageSize, long totalElements, int totalPages,
                                     boolean first, boolean last, boolean hasNext, boolean hasPrevious,
                                     List<HisabTableRow> employees) {
        this.month = month;
        this.daysInMonth = daysInMonth;
        this.totalEligibleEmployees = totalEligibleEmployees;
        this.totalFullDays = totalFullDays;
        this.totalHalfDays = totalHalfDays;
        this.totalEffectivePresenties = totalEffectivePresenties;
        this.totalOrganizationEarnings = totalOrganizationEarnings;
        this.totalOrganizationAdvance = totalOrganizationAdvance;
        this.totalOrganizationFinalMoney = totalOrganizationFinalMoney;
        this.pageNumber = pageNumber;
        this.pageSize = pageSize;
        this.totalElements = totalElements;
        this.totalPages = totalPages;
        this.first = first;
        this.last = last;
        this.hasNext = hasNext;
        this.hasPrevious = hasPrevious;
        this.employees = employees;
    }

    public String getMonth() {
        return month;
    }

    public void setMonth(String month) {
        this.month = month;
    }

    public int getDaysInMonth() {
        return daysInMonth;
    }

    public void setDaysInMonth(int daysInMonth) {
        this.daysInMonth = daysInMonth;
    }

    public int getTotalEligibleEmployees() {
        return totalEligibleEmployees;
    }

    public void setTotalEligibleEmployees(int totalEligibleEmployees) {
        this.totalEligibleEmployees = totalEligibleEmployees;
    }

    public int getTotalFullDays() {
        return totalFullDays;
    }

    public void setTotalFullDays(int totalFullDays) {
        this.totalFullDays = totalFullDays;
    }

    public int getTotalHalfDays() {
        return totalHalfDays;
    }

    public void setTotalHalfDays(int totalHalfDays) {
        this.totalHalfDays = totalHalfDays;
    }

    public double getTotalEffectivePresenties() {
        return totalEffectivePresenties;
    }

    public void setTotalEffectivePresenties(double totalEffectivePresenties) {
        this.totalEffectivePresenties = totalEffectivePresenties;
    }

    public BigDecimal getTotalOrganizationEarnings() {
        return totalOrganizationEarnings;
    }

    public void setTotalOrganizationEarnings(BigDecimal totalOrganizationEarnings) {
        this.totalOrganizationEarnings = totalOrganizationEarnings;
    }

    public BigDecimal getTotalOrganizationAdvance() {
        return totalOrganizationAdvance;
    }

    public void setTotalOrganizationAdvance(BigDecimal totalOrganizationAdvance) {
        this.totalOrganizationAdvance = totalOrganizationAdvance;
    }

    public BigDecimal getTotalOrganizationFinalMoney() {
        return totalOrganizationFinalMoney;
    }

    public void setTotalOrganizationFinalMoney(BigDecimal totalOrganizationFinalMoney) {
        this.totalOrganizationFinalMoney = totalOrganizationFinalMoney;
    }

    public int getPageNumber() {
        return pageNumber;
    }

    public void setPageNumber(int pageNumber) {
        this.pageNumber = pageNumber;
    }

    public int getPageSize() {
        return pageSize;
    }

    public void setPageSize(int pageSize) {
        this.pageSize = pageSize;
    }

    public long getTotalElements() {
        return totalElements;
    }

    public void setTotalElements(long totalElements) {
        this.totalElements = totalElements;
    }

    public int getTotalPages() {
        return totalPages;
    }

    public void setTotalPages(int totalPages) {
        this.totalPages = totalPages;
    }

    public boolean isFirst() {
        return first;
    }

    public void setFirst(boolean first) {
        this.first = first;
    }

    public boolean isLast() {
        return last;
    }

    public void setLast(boolean last) {
        this.last = last;
    }

    public boolean isHasNext() {
        return hasNext;
    }

    public void setHasNext(boolean hasNext) {
        this.hasNext = hasNext;
    }

    public boolean isHasPrevious() {
        return hasPrevious;
    }

    public void setHasPrevious(boolean hasPrevious) {
        this.hasPrevious = hasPrevious;
    }

    public List<HisabTableRow> getEmployees() {
        return employees;
    }

    public void setEmployees(List<HisabTableRow> employees) {
        this.employees = employees;
    }
}
